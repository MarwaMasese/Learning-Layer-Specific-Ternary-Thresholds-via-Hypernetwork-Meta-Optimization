"""LaTeX tables for the paper, generated from aggregated runs.

Called by ``scripts/aggregate.py --latex <dir>``. Each file reproduces one
table of the camera-ready paper (same rows, columns and grouping), so no
table number is ever typed by hand:

    paper_table1_resnet18.tex     Tab. 1  ResNet-18, CIFAR-10/100 + ImageNet
    paper_table2_imagenet.tex     Tab. 2  ImageNet, six backbones
    paper_table3_efficiency.tex   Tab. 3  params, FLOPs, accuracy, overhead
    paper_table4_ablation.tex     Tab. 4  component ablations
    paper_table5_sensitivity.tex  Tab. 5  lambda1 / lambda2 / K sensitivity
"""

from __future__ import annotations

import os

import numpy as np

MODEL_PRETTY = {
    "resnet18": "ResNet-18",
    "resnet50": "ResNet-50",
    "mobilenetv2": "MobileNetV2",
    "convnext_t": "ConvNeXt",
    "vit_s16": "ViT-S/16",
    "swin_t": "Swin-T",
}
DS_PRETTY = {
    "cifar10": "CIFAR-10",
    "cifar100": "CIFAR-100",
    "imagenet": "ImageNet",
}
EOL = r" \\"


def _write(path: str, lines: list[str]) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("% generated by scripts/aggregate.py\n")
        fh.write("% do not edit by hand: rerun aggregate.py --latex\n")
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {path}")


def _mean(runs: list, key: str) -> float:
    v = [r[key] for r in runs if r.get(key)]
    return float(np.mean(v)) if v else float("nan")


# ---------------------------------------------------------------------------
# Paper-layout tables (camera-ready Tabs. 1-5)
# ---------------------------------------------------------------------------

# (variant, label, published weight/activation setting), paper row order
PAPER_ROWS = [
    ("fp", "Full-Precision", "W32/A32"),
    ("twn", "TWN", "W1/A32"),
    ("ttq", "TTQ", r"W1$^\dagger$/A32"),
    ("rtn", "RTN", "W1/A1"),
    ("metaquant", "MetaQuant", "W1/A32"),
    ("lsq", "LSQ", "W2/A2"),
    ("fatnn", "FATNN", "W1/A1"),
    ("ours", "Ours", "W1/A32"),
]
PAPER_ABLATION_GROUPS = [
    (
        "Bilevel structure",
        [
            ("perlayer", r"Trainable $\tau^{(l)}$ per layer, no HN"),
            ("ours_joint", "Hypernetwork, joint single-level optim."),
        ],
    ),
    (
        "Statistical conditioning",
        [
            ("ours_no_gamma", r"w/o Gradient magnitude ($\gamma^{(l)}$)"),
            ("ours_no_rho", r"w/o Activation sparsity ($\rho^{(l)}$)"),
            ("ours_no_sigma", r"w/o Variance ($\sigma^{(l)}$)"),
            ("ours_mean_only", r"Mean only ($\mu^{(l)}$)"),
        ],
    ),
    (
        "Hypernetwork capacity",
        [
            ("ours_w32", r"Hidden width 32 (4$\to$32$\to$32$\to$2)"),
            ("ours_w128", r"Hidden width 128 (4$\to$128$\to$128$\to$2)"),
            ("ours_d1", r"One hidden layer (4$\to$64$\to$2)"),
            (
                "ours_d3",
                r"Three hidden layers (4$\to$64$\to$64$\to$64$\to$2)",
            ),
        ],
    ),
    (
        "Quantization design",
        [
            ("ours_symmetric", "Symmetric thresholds"),
            ("ours_linear_T", "Linear temperature decay"),
            ("ours_const_T", "No temperature annealing"),
            ("ours_ste", r"STE instead of $Q_{\mathrm{soft}}$"),
        ],
    ),
]
# (group, [(variant, lambda1, lambda2, K)]); "ours" is the default row
PAPER_SENSITIVITY = [
    (
        r"Smoothness weight $\lambda_1$",
        [
            ("ours_l1_1e-5", "-5", "-3", 5),
            ("ours", "-4", "-3", 5),
            ("ours_l1_1e-3", "-3", "-3", 5),
        ],
    ),
    (
        r"Consistency weight $\lambda_2$",
        [
            ("ours_l2_1e-4", "-4", "-4", 5),
            ("ours", "-4", "-3", 5),
            ("ours_l2_1e-2", "-4", "-2", 5),
        ],
    ),
    (
        r"Inner loop step count $K$",
        [
            ("ours_k1", "-4", "-3", 1),
            ("ours_k3", "-4", "-3", 3),
            ("ours", "-4", "-3", 5),
            ("ours_k10", "-4", "-3", 10),
        ],
    ),
]


def title_key(title: str) -> str:
    """S / C / K for the three sensitivity groups."""
    return "S" if "Smooth" in title else "C" if "Consist" in title else "K"


def _cell(s, std: bool) -> str:
    """Paper style: one decimal; optional ±std when n > 1."""
    if s is None:
        return "--"
    m, sd, n = s
    return f"${m:.1f} \\pm {sd:.1f}$" if std and n > 1 else f"{m:.1f}"


def _delta(s) -> str:
    return "--" if s is None else f"{s[0]:+.1f}"


def _method_rows(groups, cols, stat, paired, std):
    """Rows of Tabs. 1/2; ``cols`` is a list of (dataset, model)."""
    lines = [r"\midrule"]
    for v, label, pub in PAPER_ROWS:
        if not any(groups.get((ds, m, v)) for ds, m in cols):
            continue
        cells = [
            _cell(stat(groups.get((ds, m, v), []), "test"), std)
            for ds, m in cols
        ]
        if v == "ours":
            lines.append(r"\midrule")
        lines.append(f"{label} & {pub} & " + " & ".join(cells) + EOL)
        if v == "fp":
            lines.append(r"\midrule")
    cells = [
        _delta(paired(groups, ds, m, "ours", "lsq", "test")) for ds, m in cols
    ]
    lines.append(r"vs.\ LSQ & --- & " + " & ".join(cells) + EOL)
    return lines


def write_paper_tables(out_dir, groups, stat, paired, std=False) -> list:
    """Write paper_table{1..5}.tex for whatever runs exist; return names."""
    os.makedirs(out_dir, exist_ok=True)
    written = []

    def emit(name, spec, header, body):
        _write(
            os.path.join(out_dir, name),
            [
                r"\begin{tabular}{" + spec + "}",
                r"\toprule",
                header + EOL,
                *body,
                r"\bottomrule",
                r"\end{tabular}",
            ],
        )
        written.append(name)

    # Tab. 1: ResNet-18 across the three datasets
    cols = [
        (ds, "resnet18")
        for ds in ("cifar10", "cifar100", "imagenet")
        if groups.get((ds, "resnet18", "ours"))
    ]
    if cols:
        emit(
            "paper_table1_resnet18.tex",
            "ll" + "c" * len(cols),
            "Method & Pub.\\ W/A & "
            + " & ".join(DS_PRETTY[ds] for ds, _ in cols),
            _method_rows(groups, cols, stat, paired, std),
        )

    # Tab. 2: ImageNet across all backbones
    cols = [
        ("imagenet", m)
        for m in MODEL_PRETTY
        if groups.get(("imagenet", m, "ours"))
    ]
    if cols:
        emit(
            "paper_table2_imagenet.tex",
            "ll" + "c" * len(cols),
            "Method & Pub.\\ W/A & "
            + " & ".join(MODEL_PRETTY[m] for _, m in cols),
            _method_rows(groups, cols, stat, paired, std),
        )

    # Tab. 3: ImageNet efficiency. "Mem. Cost" is the peak training-memory
    # ratio of ours to the fixed baseline (same quantizer, no hypernetwork).
    rows, times = [], []
    for _, m in cols:
        o = groups[("imagenet", m, "ours")]
        f = groups.get(("imagenet", m, "fixed"), [])
        macs = o[0].get("macs")
        acc = stat(o, "test")
        hn = 100.0 * o[0]["method_params"] / o[0]["params"]
        mem = (
            _mean(o, "peak_mem_mb") / _mean(f, "peak_mem_mb")
            if f
            else float("nan")
        )
        t = (
            _mean(o, "mean_epoch_time_s") / _mean(f, "mean_epoch_time_s")
            if f
            else float("nan")
        )
        times.append(f"% {m}: time/epoch ours/fixed = {t:.2f}x")
        rows.append(
            f"{MODEL_PRETTY[m]} & {o[0]['params'] / 1e6:.1f}M & "
            + (f"{macs / 1e9:.1f}G" if macs else "--")
            + f" & {_cell(acc, std)} & {hn:.2f}\\% & "
            + rf"{mem:.2f}$\times$"
            + EOL
        )
    if rows:
        emit(
            "paper_table3_efficiency.tex",
            "lccccc",
            "Backbone & Params & FLOPs & Accuracy (\\%) & HN Overhead & "
            "Mem.\\ Cost",
            [r"\midrule", *rows, *times],
        )

    # Tabs. 4 and 5: CIFAR-10 / ResNet-18 ablations and sensitivity
    key = ("cifar10", "resnet18")
    full = stat(groups.get(key + ("ours",), []), "test")
    if full is not None:
        body = [
            r"\midrule",
            r"Full Method (4$\to$64$\to$64$\to$2) & "
            + _cell(full, std)
            + " & --"
            + EOL,
        ]
        for title, items in PAPER_ABLATION_GROUPS:
            present = [(v, lab) for v, lab in items if groups.get(key + (v,))]
            if not present:
                continue
            body += [
                r"\midrule",
                rf"\multicolumn{{3}}{{l}}{{\emph{{{title}}}}}" + EOL,
            ]
            for v, lab in present:
                s = stat(groups[key + (v,)], "test")
                d = paired(groups, *key, v, "ours", "test")
                body.append(f"{lab} & {_cell(s, std)} & {_delta(d)}" + EOL)
        emit(
            "paper_table4_ablation.tex",
            "lcc",
            r"Configuration & Top-1 (\%) & $\Delta$ vs Full",
            body,
        )

        body = []
        for title, items in PAPER_SENSITIVITY:
            body += [
                r"\midrule",
                rf"\multicolumn{{5}}{{l}}{{\emph{{{title}}}}}" + EOL,
            ]
            for v, l1, l2, k in items:
                s = stat(groups.get(key + (v,), []), "test")
                sym, val = {
                    "S": (r"\lambda_1", l1),
                    "C": (r"\lambda_2", l2),
                    "K": ("K", k),
                }[title_key(title)]
                val = val if sym == "K" else f"10^{{{val}}}"
                label = f"${sym} = {val}$" + (
                    r" (default$^\dagger$)" if v == "ours" else ""
                )
                body.append(
                    f"{label} & $10^{{{l1}}}$ & "
                    f"$10^{{{l2}}}$ & {k} & {_cell(s, std)}" + EOL
                )
        emit(
            "paper_table5_sensitivity.tex",
            "lcccc",
            r"Configuration & $\lambda_1$ & $\lambda_2$ & $K$ & Top-1 (\%)",
            body,
        )
    return written
