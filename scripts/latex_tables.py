"""LaTeX tables for the paper, generated from aggregated runs.

The paper includes these files with ``\\resulttable{<name>}``; no table number
is ever typed by hand. Called by ``scripts/aggregate.py --latex <dir>``.

Files written (per dataset ``ds``):
    <ds>_main.tex        methods x backbones, plus ours - fixed (tuned)
    <ds>_efficiency.tex  hypernetwork cost relative to the fixed run
    ablation.tex         CIFAR-10 / ResNet-18 variants of ours
"""

from __future__ import annotations

import os

import numpy as np

MODEL_PRETTY = {
    "resnet18": "ResNet-18",
    "resnet50": "ResNet-50",
    "mobilenetv2": "MobileNetV2",
    "convnext_t": "ConvNeXt-T",
    "vit_s16": "ViT-S/16",
    "swin_t": "Swin-T",
}
DS_PRETTY = {
    "cifar10": "CIFAR-10",
    "cifar100": "CIFAR-100",
    "imagenet": "ImageNet",
}
MAIN_ROWS = [
    "fp",
    "twn",
    "ttq",
    "rtn",
    "metaquant",
    "lsq",
    "fatnn",
    "fixed_tuned",
    "perlayer",
    "ours",
]
ABLATION_ROWS = [
    ("ours", "Full method"),
    ("ours_joint", "Single-level (no held-out outer loop)"),
    ("perlayer", "Free per-layer thresholds, no hypernetwork"),
    ("ours_no_gamma", r"w/o gradient magnitude $\gamma$"),
    ("ours_no_rho", r"w/o activation sparsity $\rho$"),
    ("ours_no_sigma", r"w/o activation std $\sigma$"),
    ("ours_mean_only", r"Mean $\mu$ only"),
    ("ours_w32", "Hidden width 32"),
    ("ours_w128", "Hidden width 128"),
    ("ours_d1", "One hidden layer"),
    ("ours_d3", "Three hidden layers"),
    ("ours_symmetric", "Symmetric thresholds"),
    ("ours_linear_T", "Linear temperature decay"),
    ("ours_const_T", r"No annealing ($T = T_{\min}$)"),
    ("ours_ste", "Plain STE (no soft gradient)"),
    ("ours_l1_1e-5", r"$\lambda_1 = 10^{-5}$"),
    ("ours_l1_1e-3", r"$\lambda_1 = 10^{-3}$"),
    ("ours_l2_1e-4", r"$\lambda_2 = 10^{-4}$"),
    ("ours_l2_1e-2", r"$\lambda_2 = 10^{-2}$"),
    ("ours_k1", r"$K = 1$"),
    ("ours_k3", r"$K = 3$"),
    ("ours_k10", r"$K = 10$"),
]
EOL = r" \\"


def _write(path: str, lines: list[str]) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("% generated by experimentswacv/scripts/aggregate.py\n")
        fh.write("% do not edit by hand: rerun aggregate.py --latex\n")
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {path}")


def _mean(runs: list, key: str) -> float:
    v = [r[key] for r in runs if r.get(key)]
    return float(np.mean(v)) if v else float("nan")


def write_latex(
    out_dir, ds, models, groups, metric, stat, paired, fmt, pretty
) -> None:
    """Write every table for dataset ``ds`` into ``out_dir``."""
    os.makedirs(out_dir, exist_ok=True)

    # main table
    head = (
        rf"\textbf{{{DS_PRETTY.get(ds, ds)}}} & "
        + " & ".join(MODEL_PRETTY.get(m, m) for m in models)
        + EOL
    )
    lines = [
        r"\begin{tabular}{l" + "c" * len(models) + "}",
        r"\toprule",
        head,
        r"\midrule",
    ]
    for v in MAIN_ROWS:
        if not any(groups.get((ds, m, v)) for m in models):
            continue
        cells = [
            fmt(stat(groups.get((ds, m, v), []), metric), latex=True)
            for m in models
        ]
        lines.append(f"{pretty[v]} & " + " & ".join(cells) + EOL)
        if v == "fp":
            lines.append(r"\midrule")
    cells = [
        fmt(paired(groups, ds, m, "ours", "fixed_tuned", metric), latex=True)
        for m in models
    ]
    lines += [
        r"\midrule",
        r"Ours $-$ fixed (tuned), paired & " + " & ".join(cells) + EOL,
        r"\bottomrule",
        r"\end{tabular}",
    ]
    _write(os.path.join(out_dir, f"{ds}_main.tex"), lines)

    # efficiency: hypernetwork cost relative to the fixed-threshold run
    rows = []
    for m in models:
        o = groups.get((ds, m, "ours"), [])
        f = groups.get((ds, m, "fixed"), [])
        if not (o and f):
            continue
        hn = o[0]["method_params"] / o[0]["params"] * 100
        t = _mean(o, "mean_epoch_time_s") / _mean(f, "mean_epoch_time_s")
        mem = _mean(o, "peak_mem_mb") / _mean(f, "peak_mem_mb")
        rows.append(
            f"{MODEL_PRETTY.get(m, m)} & "
            f"{o[0]['params'] / 1e6:.1f}M & "
            f"{o[0]['num_ternary_layers']} & {hn:.3f}\\% & "
            rf"{t:.2f}$\times$ & {mem:.2f}$\times$" + EOL
        )
    if rows:
        _write(
            os.path.join(out_dir, f"{ds}_efficiency.tex"),
            [
                r"\begin{tabular}{lccccc}",
                r"\toprule",
                "Backbone & Params & Ternary layers & HN params & "
                "Time/epoch & Peak memory" + EOL,
                r"\midrule",
                *rows,
                r"\bottomrule",
                r"\end{tabular}",
            ],
        )

    # ablation: CIFAR-10 / ResNet-18 variants of ours
    if ds == "cifar10" and groups.get((ds, "resnet18", "ours")):
        rows = []
        for v, label in ABLATION_ROWS:
            runs = groups.get((ds, "resnet18", v), [])
            if not runs:
                continue
            d = (
                paired(groups, ds, "resnet18", v, "ours", metric)
                if v != "ours"
                else None
            )
            rows.append(
                f"{label} & {fmt(stat(runs, metric), latex=True)} & "
                f"{fmt(d, latex=True) if d else '--'}" + EOL
            )
        _write(
            os.path.join(out_dir, "ablation.tex"),
            [
                r"\begin{tabular}{lcc}",
                r"\toprule",
                r"Configuration & Top-1 (\%) & $\Delta$ vs.\ full (paired)"
                + EOL,
                r"\midrule",
                *rows,
                r"\bottomrule",
                r"\end{tabular}",
            ],
        )
